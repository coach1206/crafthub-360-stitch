const SUPPORTED_LANGS = Object.keys(LOCALES)

export function tEventPackage(key, locale = 'en-US') {
  const lang = LOCALES[locale] || LOCALES['en-US']
  return lang[key] ?? LOCALES['en-US'][key] ?? key
}

export function getSupportedEventPackageLanguages() {
  return [...SUPPORTED_LANGS]
}
