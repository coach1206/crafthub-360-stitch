export function getEducationalTile(tileId, craftType = null) {
  return EDUCATIONAL_TILES.find(t =>
    t.tileId === tileId && (!craftType || t.craftType === craftType)
  ) ?? null
}

export function getTilesByCraft(craftType) {
  return EDUCATIONAL_TILES.filter(t => t.craftType === craftType)
}

export function getTilesByCategory(craftType, category) {
  return EDUCATIONAL_TILES.filter(t => t.craftType === craftType && t.category === category)
}

export function getAllCraftsWithTiles() {
  const crafts = [...new Set(EDUCATIONAL_TILES.map(t => t.craftType))]
  return crafts.map(craftType => ({
    craftType,
    tileCount: EDUCATIONAL_TILES.filter(t => t.craftType === craftType).length,
  }))
}
